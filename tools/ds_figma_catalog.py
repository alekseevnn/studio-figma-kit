#!/usr/bin/env python3
"""Writes the gallery's "Product components (Figma)" section (ds/index.html, between the figma-catalog markers) from a
read of the AITV DS product page (1887:3092) and the thumbnails in ds/assets/fig/.
Usage: python3 tools/ds_figma_catalog.py <components.json> [checked date]
components.json = rows [section, name, nodeId, variantCount, props, description, w, h] (the use_figma read in
WORKFLOW.md → "DS gallery: product components"). Thumbnails: ds/assets/fig/<slug>.webp with ds/assets/fig/index.json."""
import json, sys, os, re, html
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(sys.argv[1])); checked = sys.argv[2] if len(sys.argv) > 2 else ''
thumbs = json.load(open(os.path.join(ROOT, 'ds/assets/fig/index.json'))) if os.path.exists(os.path.join(ROOT, 'ds/assets/fig/index.json')) else {}
slug = lambda n: re.sub(r'[^a-z0-9]+', '-', n.lower()).strip('-')
def clean(s):
    for _ in range(4): s = html.unescape(s)
    return s
def props_html(p):
    out = []
    for k, v in p.items():
        if isinstance(v, list): out.append(f'<span class="fc-p"><b>{html.escape(k)}</b> {html.escape(" · ".join(v))}</span>')
        else: out.append(f'<span class="fc-p"><b>{html.escape(k)}</b> <i>{v}</i></span>')
    return ''.join(out)
secs = []
for r in rows:
    if not secs or secs[-1][0] != r[0]: secs.append((r[0], []))
    secs[-1][1].append(r)
parts = []
nav = []
for name, items in secs:
    sid = 'fc-' + slug(name); nav.append(f'<a href="#{sid}">{html.escape(name)}</a>')
    cards = []
    for sec, n, nid, nv, props, desc, w, h in items:
        s = slug(n); t = thumbs.get(s)
        link = 'https://www.figma.com/design/k1ddhR3yVccI0N0A0SJGqz/AITV-DS?node-id=' + nid.replace(':', '-')
        img = f'<a class="fc-img" href="{link}"><img loading="lazy" src="assets/fig/{s}.webp" alt="" width="{t["w"]}" height="{t["h"]}"></a>' if t else ''
        d = clean(desc); d = d if len(d) < 250 else d[:d.rfind(' ', 0, 250)] + ' …'
        cards.append(f'<article class="fc">{img}<div class="fc-b"><h3 class="t-label-medium"><a href="{link}">{html.escape(n)}</a></h3>'
                     f'<span class="t-paragraph-x-small fc-n">{nv} variant{"s" if nv != 1 else ""}</span>'
                     f'<p class="t-paragraph-small">{html.escape(d)}</p><div class="fc-ps t-paragraph-x-small">{props_html(props)}</div></div></article>')
    parts.append(f'<h3 class="t-title-h6 fc-sec" id="{sid}">{html.escape(name)} <span class="t-paragraph-small sub">{len(items)}</span></h3><div class="fc-grid">{"".join(cards)}</div>')
total = len(rows); variants = sum(r[3] for r in rows)
section = f'''<!-- figma-catalog:begin (generated by tools/ds_figma_catalog.py; don't edit by hand) -->
    <section id="product">
      <style>
        #product .fc-grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:16px;margin-bottom:40px}}
        #product .fc{{background:var(--bg-1);border-radius:var(--radius-16);overflow:hidden;display:flex;flex-direction:column;box-shadow:inset 0 0 0 1px var(--w5)}}
        #product .fc-img{{display:flex;align-items:center;justify-content:center;height:180px;padding:16px;box-shadow:inset 0 -1px 0 var(--w5)}}
        #product .fc-img img{{max-width:100%;max-height:100%;width:auto;height:auto;object-fit:contain}}
        #product .fc-b{{padding:16px;display:flex;flex-direction:column;gap:6px}}
        #product .fc-b h3{{margin:0}} #product .fc-b h3 a{{color:var(--text-primary);text-decoration:none}}
        #product .fc-b p{{margin:0;color:var(--text-secondary)}} #product .fc-n{{color:var(--text-tertiary)}}
        #product .fc-ps{{display:flex;flex-direction:column;gap:2px;color:var(--text-tertiary)}} #product .fc-p b{{color:var(--text-secondary);font-weight:500}}
        #product .fc-sec{{margin:8px 0 16px}} #product .fc-nav{{display:flex;flex-wrap:wrap;gap:8px 16px;margin:0 0 24px}}
      </style>
      <div class="sh"><h2 class="t-title-h5" style="margin:0"><a href="https://www.figma.com/design/k1ddhR3yVccI0N0A0SJGqz/AITV-DS?node-id=1887-3092" style="color:inherit">Product components</a> <span class="pill" style="vertical-align:middle">Figma</span></h2>
        <p>The product's own components (header, cards, player, sheets, dialogs …), on the DS file's product page: {total} components with {variants} variants{(", read from Figma on " + checked) if checked else ""}. Figma is the source: use them as instances there, and in code build them from the DS tokens and text styles as the prototype <code>p-4f6cb6</code> does. Each card links to the component in Figma; its description there has the exact values and where each variant is used.</p></div>
      <nav class="fc-nav t-label-small">{"".join(nav)}</nav>
      {"".join(parts)}
    </section>
<!-- figma-catalog:end -->'''
p = os.path.join(ROOT, 'ds/index.html'); s = open(p).read()
if '<!-- figma-catalog:begin' in s:
    s = re.sub(r'<!-- figma-catalog:begin.*?<!-- figma-catalog:end -->', lambda m: section, s, flags=re.S)
else:
    s = s.replace('    <section id="toggle">', section + '\n\n    <section id="toggle">', 1)
    s = s.replace('<a href="#toggle">Toggle motion</a>', '<a href="#toggle">Toggle motion</a>\n    <span class="grp t-subheading-x-small sub">Product (Figma)</span>\n    <a href="#product">Product components</a>', 1)
open(p, 'w').write(s)
print('components', total, 'variants', variants, 'thumbs', len(thumbs))
