#!/usr/bin/env python3
"""Build the AITV DS block from ds/tokens.json + ds/components.css.

Usage: python3 tools/ds_build.py

Writes
- ds/tokens.css  generated CSS custom properties and text-style classes (never edit by hand)
- ds/ds.css      tokens.css + components.css, the block tools/ds_sync.py inlines into every prototype
- ds/VERSION     short hash of ds.css + ds.js, stamped into each prototype's block

Naming
- primitives: --neutral-0 … --neutral-950, --accent-primary-*, --accent-secondary-*, --red-300/500/700 …
- alphas: --white-a3/5/10/24, --neutral-a24/60/80, --primary-a5/10/24, --red-a5 …
- semantic: --bg-0…3 (background level-0…3), --text-*, --icon-*, --accents-darker/dark/base/light/lighter
- short names kept for the prototypes written before ds/: --w3/5/10/24, --n24/60/80, --accent, --red/--green/--yellow
- --radius-0…28 and --radius-full, --space-0…48, --shadow-x-small/small/medium/large, --ff-text, --ff-display
- text styles: classes .t-title-h5, .t-label-small, .t-subheading-x-small …, and for CSS that sets its own type
  font:var(--t-label-small); letter-spacing:var(--t-label-small-ls)
"""
import json, re, hashlib, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DS = os.path.join(ROOT, 'ds')

def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')

def var_of(ref, tok):
    """CSS var for a colour or alpha token name like 'neutral/950' or 'white/alpha-3'."""
    group, step = ref.split('/')
    if step.startswith('alpha-'): return f'--{group}-a{step[6:]}'
    return f'--{group}-{step}'

def build():
    tok = json.load(open(os.path.join(DS, 'tokens.json')))
    L = []
    L.append('/* AITV DS tokens, generated by tools/ds_build.py from ds/tokens.json (Figma ' + tok['$source']['fileKey'] + ', pulled ' + tok['$source']['pulled'] + '). Do not edit. */')
    L.append(':root{')
    L.append('  /* 04-Foundations */')
    for k, v in tok['color'].items(): L.append(f'  {var_of(k, tok)}:{v};')
    for k, v in tok['alpha'].items(): L.append(f'  {var_of(k, tok)}:{v};')
    L.append('  /* 03-Tokens */')
    sem_names = {'bg/level-0': '--bg-0', 'bg/level-1': '--bg-1', 'bg/level-2': '--bg-2', 'bg/level-3': '--bg-3'}
    for k, ref in tok['semantic'].items():
        name = sem_names.get(k) or '--' + slug(k)
        L.append(f'  {name}:var({var_of(ref, tok)});')
    L.append('  /* short names used across the prototypes */')
    L.append('  --w3:var(--white-a3); --w5:var(--white-a5); --w10:var(--white-a10); --w24:var(--white-a24);')
    L.append('  --n24:var(--neutral-a24); --n60:var(--neutral-a60); --n80:var(--neutral-a80);')
    L.append('  --accent:var(--accents-lighter); --red:var(--red-500); --green:var(--green-500); --yellow:var(--yellow-500);')
    L.append('  /* 01-Radius · 02-Spacing · effect styles */')
    L.append('  ' + ' '.join(f'--radius-{k}:{v}px;' for k, v in tok['radius'].items()))
    L.append('  ' + ' '.join(f'--space-{k}:{v}px;' for k, v in tok['spacing'].items()))
    for k, v in tok['shadow'].items(): L.append(f'  --shadow-{k}:{v};')
    L.append('  /* type */')
    L.append(f"  --ff-text:{tok['font']['text']};")
    L.append(f"  --ff-display:{tok['font']['display']};")
    for name, s in tok['text'].items():
        n = slug(name); fam = 'var(--ff-display)' if s['family'] == 'display' else 'var(--ff-text)'
        ls = '0' if not s['tracking'] else ('%gem' % round(s['tracking'] / 100, 4))
        L.append(f"  --t-{n}:{s['weight']} {s['size']}px/{s['line']}px {fam}; --t-{n}-ls:{ls};")
    L.append('  /* motion (code-first: not in Figma) */')
    L.append('  --ds-ease:cubic-bezier(.22,1,.36,1);')
    L.append('}')
    L.append('/* Text styles. Titles are Inter at its default optical size, as in Figma (Can, 20 Oct 2026: Inter Display dropped). */')
    for name, s in tok['text'].items():
        n = slug(name)
        extra = 'font-variation-settings:normal;'
        extra += 'font-optical-sizing:none;font-feature-settings:inherit;font-kerning:inherit;'   # the font shorthand resets these
        if s.get('upper'): extra += 'text-transform:uppercase;'
        L.append(f'.t-{n}{{font:var(--t-{n});letter-spacing:var(--t-{n}-ls);{extra}}}')
    tokens_css = '\n'.join(L) + '\n'
    open(os.path.join(DS, 'tokens.css'), 'w').write(tokens_css)
    comp = open(os.path.join(DS, 'components.css')).read()
    ds_css = tokens_css + '\n' + comp
    open(os.path.join(DS, 'ds.css'), 'w').write(ds_css)
    js = open(os.path.join(DS, 'ds.js')).read()
    ver = hashlib.sha256((ds_css + js).encode()).hexdigest()[:8]
    open(os.path.join(DS, 'VERSION'), 'w').write(ver + '\n')
    print('ds.css', len(ds_css), 'bytes · ds.js', len(js), 'bytes · version', ver)
    return ver

if __name__ == '__main__':
    build()
